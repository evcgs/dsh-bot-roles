// The Bot-team import face.
//
// DS Bot exposes no creation API — `create_bot` is a model-facing tool and the
// roster lives inside DS Bot's own state, deliberately closed to other plugins. So
// the honest way to turn this catalog into Bots is a prompt the user pastes into
// their Main Bot, which then makes the calls itself. This module renders that
// prompt, with the roster inlined so it works even where the repo is not reachable.

/**
 * @param {Array<Record<string, any>>} roles
 * @param {Record<string, any>} catalog
 * @returns {string} markdown
 */
export function botTeamPrompt(roles, catalog) {
  const lines = []
  lines.push('# Bot team import prompt')
  lines.push('')
  lines.push('<!-- Generated by scripts/build.mjs from roles/roles.json — do not edit by hand. -->')
  lines.push('')
  lines.push(
    `This file turns the ${roles.length} roles in this pack into living Bots. DS Bot creates Bots only through its own tools, so nothing can install them for you: copy everything below the horizontal rule into your **Main Bot** and send it.`,
  )
  lines.push('')
  lines.push('---')
  lines.push('')
  lines.push('## 任务：把下面这份团队名单建成 Bot')
  lines.push('')
  lines.push(`请用 create_bot 工具按下面的 ${roles.length} 条记录建立 Bot 团队。执行要求：`)
  lines.push('')
  lines.push('1. 先调用 list_bots 查重：已有同名 Bot 就跳过，不要重复创建，也不要改名覆盖。')
  lines.push('2. `name` / `role` / `color` 原样使用；`instructions` 原样写入，一个字都不要改写、不要总结。')
  lines.push('3. `instructions` 里的 `{{cwd}}` 替换为本团队的**工作区绝对路径**；我没指定时用当前会话的工作目录。')
  lines.push(`4. \`instructions\` 里提到 \`skill: X\` 的地方是可选增强：部署里没有该 skill 时保留原文即可，岗位会自行降级说明。`)
  lines.push('5. `model` 一栏是导出时的原值，仅供参考：只有当这个 provider/model 在你的部署里确实可用时才传 `model`；否则一律不传，用部署默认模型。')
  lines.push('6. 逐条创建，一条失败不要中断后续；全部结束后用一段话回报：建成了哪些、跳过了哪些、失败的具体原因。')
  lines.push('')
  lines.push('不要替这些 Bot 编造能力：它们的话术里已经写明「工具不可用就如实说明、绝不假装调用」。')
  lines.push('')
  lines.push(`## 团队名单（${roles.length} 个岗位）`)
  lines.push('')
  for (const [index, role] of roles.entries()) {
    lines.push(`### ${index + 1}. ${role.name} ｜ role: \`${role.roleLabel}\` ｜ color: \`${role.color}\``)
    lines.push('')
    lines.push(`- 定位：${role.description}`)
    lines.push(`- 导出时模型：\`${catalog.exportedModels?.[role.name] ?? '(部署默认)'}\``)
    lines.push('- instructions:')
    lines.push('')
    lines.push('```text')
    const body = role.localNotes ? `${role.instructions}\n\n${role.localNotes}` : role.instructions
    // The workspace token is spelled out here so the reader substitutes a real path.
    lines.push(body.replaceAll('{{cwd}}', '<工作区绝对路径>'))
    lines.push('```')
    lines.push('')
  }
  lines.push('---')
  lines.push('')
  lines.push(
    'Source of truth: `roles/roles.json` in this repository. Editing a role there and re-running `npm run build` regenerates this prompt, `bots/roster.json`, and the preset files together.',
  )
  lines.push('')
  return lines.join('\n')
}
